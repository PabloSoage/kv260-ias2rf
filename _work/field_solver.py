#!/usr/bin/env python3
"""
Trace impedances for the chosen fabricator stackup, by a 2D field solver.

The closed forms in stackup_impedance.py (IPC-2141, Hammerstad-Jensen) are
good to about +/-10 % and cannot model the solder mask, which lowers a surface
trace's impedance by several ohms. This solves Laplace's equation on the
cross-section instead:

  * finite differences on a uniform grid (5 um), permittivity per cell;
  * conductors held at fixed potential, the box edges grounded far away;
  * C from the field energy, with the dielectrics (C) and without (C0);
  * Z0 = 1 / (c * sqrt(C * C0)); for a pair, the odd mode, Zdiff = 2 Z_odd.

Checked on start against two exact results: a symmetric zero-thickness
stripline (Cohn's elliptic-integral formula) and a wide-box microstrip against
Hammerstad-Jensen, which is accurate to about 1 % in that range.

Stackup: JLCPCB JLC06161H-2116A, 6 layers, 1.6 mm (1.556 mm nominal), outer
1 oz, inner 0.5 oz, NP-155F laminate. Layer data from JLCPCB's own stackup
API, as extracted by github.com/gsuberland/jlcpcb_autogenerated_stackups
(normalised_json, fetched 26 Sep 2026); dielectric constants as on
jlcpcb.com/impedance. Solder mask 1.2 mil on laminate, 0.6 mil on copper, as
JLCPCB's impedance calculator guide states; its Er (3.8) is an estimate.

Needs numpy and scipy (pip install numpy scipy).

Usage:  py _work/field_solver.py
"""

import math
import sys

import numpy as np
import scipy.sparse as sp
import scipy.sparse.linalg as spla
from scipy.special import ellipk

E0 = 8.8541878128e-12
C_LIGHT = 299792458.0
D = 0.005                      # grid step, mm

# ---- JLC06161H-2116A, from the top (mm) --------------------------------
T_OUT, T_IN = 0.035, 0.0152
PP_2116, ER_2116 = 0.1164, 4.16
CORE_THIN, ER_CORE_THIN = 0.13, 4.17
CORE_MID, ER_CORE_MID = 0.70, 4.53
MASK_LAM, MASK_CU, ER_MASK = 0.0305, 0.0152, 3.8


class Grid:
    """Nodes on a D-spaced grid; eps per cell; fixed potentials at nodes."""

    def __init__(self, width, height):
        self.nx = int(round(width / D)) + 1
        self.ny = int(round(height / D)) + 1
        self.eps = np.ones((self.nx - 1, self.ny - 1))
        self.fixed = np.full((self.nx, self.ny), np.nan)
        self.fixed[0, :] = self.fixed[-1, :] = 0.0
        self.fixed[:, 0] = self.fixed[:, -1] = 0.0

    def ix(self, x):
        return int(round(x / D))

    def layer(self, y0, y1, er, x0=None, x1=None):
        i0 = 0 if x0 is None else self.ix(x0)
        i1 = self.nx - 1 if x1 is None else self.ix(x1)
        self.eps[i0:i1, self.ix(y0):self.ix(y1)] = er

    def plane(self, y):
        self.fixed[:, self.ix(y)] = 0.0

    def conductor(self, x0, x1, y0, y1, v):
        self.fixed[self.ix(x0):self.ix(x1) + 1, self.ix(y0):self.ix(y1) + 1] = v

    def energy_c(self, eps=None):
        """Solve, and return eps0 * sum(eps_edge * dV^2) (F/m)."""
        eps = self.eps if eps is None else eps
        nx, ny = self.nx, self.ny
        pad = np.pad(eps, 1, mode="edge")
        # edge permittivities: x-edges between (i,j)-(i+1,j) see cells (i,j-1),(i,j)
        ex = 0.5 * (pad[1:-1, :-1] + pad[1:-1, 1:])          # (nx-1, ny)
        ey = 0.5 * (pad[:-1, 1:-1] + pad[1:, 1:-1])          # (nx, ny-1)
        free = np.isnan(self.fixed)
        idx = -np.ones((nx, ny), dtype=np.int64)
        idx[free] = np.arange(free.sum())
        n = int(free.sum())
        rows, cols, vals = [], [], []
        b = np.zeros(n)
        diag = np.zeros(n)
        V0 = np.nan_to_num(self.fixed)

        def link(ia, ja, ib, jb, w):
            # edge between node a and node b with weight w (arrays)
            a, bb = idx[ia, ja], idx[ib, jb]
            fa, fb = free[ia, ja], free[ib, jb]
            m = fa
            np.add.at(diag, a[m], w[m])
            both = fa & fb
            rows.append(a[both]); cols.append(bb[both]); vals.append(-w[both])
            onlya = fa & ~fb
            np.add.at(b, a[onlya], w[onlya] * V0[ib, jb][onlya])
        I, J = np.meshgrid(np.arange(nx - 1), np.arange(ny), indexing="ij")
        link(I, J, I + 1, J, ex)
        link(I + 1, J, I, J, ex)
        I, J = np.meshgrid(np.arange(nx), np.arange(ny - 1), indexing="ij")
        link(I, J, I, J + 1, ey)
        link(I, J + 1, I, J, ey)
        A = sp.csr_matrix((np.concatenate(vals + [diag]),
                           (np.concatenate(rows + [np.arange(n)]),
                            np.concatenate(cols + [np.arange(n)]))), shape=(n, n))
        x = spla.spsolve(A.tocsc(), b)
        V = V0.copy()
        V[free] = x
        w = (ex * np.diff(V, axis=0) ** 2).sum() + (ey * np.diff(V, axis=1) ** 2).sum()
        return E0 * w


def impedance(build, pair):
    """build(grid, odd) -> grid with conductors; returns Z0 or Zdiff."""
    g = build(odd=pair)
    c = g.energy_c()
    c0 = g.energy_c(np.ones_like(g.eps))
    if pair:                     # two conductors at +-1: energy = 2 * (1/2) C_odd
        c, c0 = c / 2, c0 / 2
    z = 1 / (C_LIGHT * math.sqrt(c * c0))
    return 2 * z if pair else z


# ---- cross-sections --------------------------------------------------------
BOX_W = 3.0


def microstrip(w, s=None, mask=True):
    """L1 over L2 (2116, 0.1164 mm), 35 um copper, solder mask on top."""
    def build(odd):
        top = PP_2116 + T_OUT + 1.2
        g = Grid(BOX_W, top)
        g.layer(0, PP_2116, ER_2116)
        xs = [(BOX_W - w) / 2] if not odd else [BOX_W / 2 - s / 2 - w, BOX_W / 2 + s / 2]
        if mask:
            g.layer(PP_2116, PP_2116 + MASK_LAM, ER_MASK)
            for x in xs:
                g.layer(PP_2116, PP_2116 + T_OUT + MASK_CU, ER_MASK, x - MASK_CU, x + w + MASK_CU)
        for k, x in enumerate(xs):
            g.conductor(x, x + w, PP_2116, PP_2116 + T_OUT, 1.0 if k == 0 else -1.0)
        return g
    return build


def stripline_l3(w, s=None):
    """L3: 0.13 mm core up to L2; 2116 + 0.7 core + 2116 down to L4. The
    trace is etched on the core's underside and sits in the 2116 below."""
    def build(odd):
        y_l4 = 0.0
        y_trace = PP_2116 + CORE_MID + PP_2116                # core underside
        y_l2 = y_trace + CORE_THIN
        g = Grid(BOX_W, y_l2)
        g.layer(0, PP_2116, ER_2116)
        g.layer(PP_2116, PP_2116 + CORE_MID, ER_CORE_MID)
        g.layer(PP_2116 + CORE_MID, y_trace, ER_2116)
        g.layer(y_trace, y_l2, ER_CORE_THIN)
        xs = [(BOX_W - w) / 2] if not odd else [BOX_W / 2 - s / 2 - w, BOX_W / 2 + s / 2]
        for k, x in enumerate(xs):
            g.conductor(x, x + w, y_trace - T_IN, y_trace, 1.0 if k == 0 else -1.0)
        return g
    return build


def solve_width(zfn, target, lo=0.04, hi=0.8):
    """Secant-bisection on width for a falling Z(w)."""
    zlo, zhi = zfn(lo), zfn(hi)
    for _ in range(30):
        mid = lo + (hi - lo) * (zlo - target) / (zlo - zhi)
        mid = min(max(mid, lo + 0.1 * (hi - lo)), hi - 0.1 * (hi - lo))
        zm = zfn(mid)
        if abs(zm - target) < 0.2 or hi - lo < 0.0005:
            return mid, zm
        if zm > target:
            lo, zlo = mid, zm
        else:
            hi, zhi = mid, zm
    return mid, zm


# ---- self-checks ---------------------------------------------------------
def check():
    # symmetric stripline, zero thickness: Z = 30 pi / sqrt(er) * K(k) / K(k'),
    # k = sech(pi w / 2b) (Cohn)
    b, w, er = 0.4, 0.2, 4.0

    def build(odd):
        g = Grid(BOX_W, b)
        g.layer(0, b, er)
        g.conductor((BOX_W - w) / 2, (BOX_W + w) / 2, b / 2, b / 2, 1.0)
        return g
    k = 1 / math.cosh(math.pi * w / (2 * b))
    exact = 30 * math.pi / math.sqrt(er) * ellipk(k * k) / ellipk(1 - k * k)
    got = impedance(build, False)
    print(f"  check: stripline b 0.4 w 0.2 er 4: solver {got:.2f}, Cohn {exact:.2f} ohm")
    assert abs(got / exact - 1) < 0.02
    # microstrip without mask against Hammerstad-Jensen (t = 0)
    w, h, er = 0.2, PP_2116, ER_2116

    def build2(odd):
        g = Grid(BOX_W, h + 1.5)
        g.layer(0, h, er)
        g.conductor((BOX_W - w) / 2, (BOX_W + w) / 2, h, h, 1.0)
        return g
    u = w / h
    ee = (er + 1) / 2 + (er - 1) / 2 * (1 + 12 / u) ** -0.5
    hj = (120 * math.pi / math.sqrt(ee)) / (u + 1.393 + 0.667 * math.log(u + 1.444)) if u > 1 else \
        60 / math.sqrt(ee) * math.log(8 / u + u / 4)
    got = impedance(build2, False)
    print(f"  check: microstrip w 0.2 h {h} er {er}: solver {got:.2f}, Hammerstad {hj:.2f} ohm")
    assert abs(got / hj - 1) < 0.03


def main():
    print("JLC06161H-2116A: L1 35um | 2116 0.1164 er4.16 | L2 | core 0.13 er4.17 | L3 |"
          " 2116+core0.70+2116 0.933 | L4 | core 0.13 | L5 | 2116 0.1164 | L6 35um")
    check()
    out = {}
    w, z = solve_width(lambda w: impedance(microstrip(w), False), 50.0)
    out["L1 50 SE"] = (w, None, z)
    for s in (0.127, 0.15, 0.2):
        w, z = solve_width(lambda w, s=s: impedance(microstrip(w, s), True), 100.0)
        out[f"L1 100 diff S{s}"] = (w, s, z)
    w, z = solve_width(lambda w: impedance(stripline_l3(w), False), 50.0)
    out["L3 50 SE"] = (w, None, z)
    for s in (0.15, 0.2):
        w, z = solve_width(lambda w, s=s: impedance(stripline_l3(w, s), True), 100.0)
        out[f"L3 100 diff S{s}"] = (w, s, z)
    print()
    for k, (w, s, z) in out.items():
        print(f"  {k:20s} W = {w * 1000:5.0f} um" + (f"  S = {s * 1000:4.0f} um" if s else " " * 13)
              + f"   -> {z:6.1f} ohm")
    # mesh convergence: the recommended pair again at half the grid step
    global D
    w, s, z = out["L1 100 diff S0.15"]
    D = 0.0025
    z2 = impedance(microstrip(w, s), True)
    D = 0.005
    print(f"\n  mesh check, L1 pair W {w * 1000:.0f} S {s * 1000:.0f}: {z:.1f} ohm at 5 um, "
          f"{z2:.1f} ohm at 2.5 um")
    # the chosen geometries, and what the unmasked closed form would say
    w_no, z_no = solve_width(lambda w: impedance(microstrip(w, mask=False), False), 50.0)
    print(f"\n  without solder mask, L1 50 ohm would be W = {w_no * 1000:.0f} um: "
          f"the mask is worth {abs(out['L1 50 SE'][0] - w_no) * 1000:.0f} um")
    return 0


if __name__ == "__main__":
    sys.exit(main())
