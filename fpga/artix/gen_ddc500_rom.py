"""Writes ddc500_rom.v: the quarter-wave sine table of the Rev08 G-7 500 MSPS DDC (ddc_500.v).

T[k] = round(4095 * sin(pi/2 * (k + 0.5) / 1024)), k = 0..1023. The half-step offset makes the quarter wave
mirror exactly (T[1023 - k] is the cosine of the angle T[k] is the sine of), so the NCO needs no special case
at 0 or 90 degrees; it turns the phase truncation into a rounding (a constant 0.044 degree phase offset).
Run it from this directory: python gen_ddc500_rom.py
"""
import math
import os

N = 1024
AMP = 4095
vals = [int(round(AMP * math.sin(math.pi / 2 * (k + 0.5) / N))) for k in range(N)]
assert max(vals) == AMP and min(vals) >= 0

lines = [
    "// SPDX-License-Identifier: Apache-2.0",
    "// GENERATED by gen_ddc500_rom.py, do not edit. Rev08 G-7: quarter-wave sine table of ddc_500.v,",
    "// T[k] = round(4095 * sin(pi/2 * (k + 0.5) / 1024)). Two read ports (the sine's and the cosine's index),",
    "// one RAMB18 per instance.",
    "",
    "`timescale 1ns/1ps",
    "`default_nettype none",
    "",
    "module ddc500_rom (",
    "    input  wire        clk,",
    "    input  wire [9:0]  addr_a,",
    "    input  wire [9:0]  addr_b,",
    "    output reg  [11:0] dout_a,",
    "    output reg  [11:0] dout_b",
    ");",
    "    (* rom_style = \"block\" *) reg [11:0] rom [0:1023];",
    "    initial begin",
]
for k, v in enumerate(vals):
    lines.append(f"        rom[{k}] = 12'd{v};")
lines += [
    "    end",
    "    always @(posedge clk) begin",
    "        dout_a <= rom[addr_a];",
    "        dout_b <= rom[addr_b];",
    "    end",
    "endmodule",
    "`default_nettype wire",
    "",
]
out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "ddc500_rom.v")
with open(out, "w", newline="\n") as f:
    f.write("\n".join(lines))
print("wrote", out)
